// Fungsi bantu bersama untuk semua halaman yang memakai AJAX.
// Dimuat lewat base.html supaya tidak perlu disalin ke tiap template.

// Mengubah karakter khusus HTML menjadi teks biasa sebelum disisipkan lewat innerHTML.
function escapeHtml(value) {
  return String(value ?? '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

// Mengambil nilai cookie berdasarkan nama, dipakai untuk header X-CSRFToken.
function getCookie(name) {
  let cookieValue = null;
  if (document.cookie && document.cookie !== '') {
    const cookies = document.cookie.split(';');
    for (let i = 0; i < cookies.length; i++) {
      const cookie = cookies[i].trim();
      if (cookie.substring(0, name.length + 1) === (name + '=')) {
        cookieValue = decodeURIComponent(cookie.substring(name.length + 1));
        break;
      }
    }
  }
  return cookieValue;
}
